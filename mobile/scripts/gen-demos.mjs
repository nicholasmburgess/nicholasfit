// Writes src/demoImages.ts: the website's demo photos (../public/demos) bundled into the app so they
// work with no signal. Re-run after scripts/fetch-exercises.mjs adds exercises: node scripts/gen-demos.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "..", "public", "demos");
const lines = readdirSync(dir)
  .filter((id) => !id.startsWith("."))
  .sort()
  .map((id) => {
    const frames = readdirSync(join(dir, id)).filter((f) => f.endsWith(".jpg")).sort();
    return `  ${JSON.stringify(id)}: [${frames.map((f) => `require(${JSON.stringify(`../../public/demos/${id}/${f}`)})`).join(", ")}],`;
  });

writeFileSync(
  join(import.meta.dirname, "..", "src", "demoImages.ts"),
  `// Generated by scripts/gen-demos.mjs. Do not edit by hand.\nimport type { ImageSourcePropType } from "react-native";\n\nexport const BUNDLED_DEMOS: Record<string, ImageSourcePropType[]> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`Bundled ${lines.length} exercise demos.`);
